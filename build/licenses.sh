#!/usr/bin/env bash
# Writes internal/legal/THIRD_PARTY_LICENSES.txt: the license (and NOTICE) of every module compiled
# into any Quay build — macOS, Windows and Linux, GUI and CLI — plus Go's own. Run `make licenses`
# after changing dependencies; the file is embedded in the binary (`quay licenses`) and shipped in
# every package.
set -euo pipefail
cd "$(dirname "$0")/.."
out=internal/legal/THIRD_PARTY_LICENSES.txt
main=$(go list -m)

# Every build configuration the Makefile produces.
targets=(
  "darwin arm64 1 production" "darwin amd64 1 production"
  "linux amd64 1 production,gtk3" "linux arm64 1 production,gtk3"
  "windows amd64 0 production" "windows arm64 0 production"
  "darwin arm64 0 nogui" "linux amd64 0 nogui" "windows amd64 0 nogui"
)
# "module version moduleDir packageDir" for every compiled package.
pkgs=$(for t in "${targets[@]}"; do
  read -r os arch cgo tags <<<"$t"
  GOOS=$os GOARCH=$arch CGO_ENABLED=$cgo go list -deps -tags "$tags" \
    -f '{{with .Module}}{{.Path}} {{.Version}} {{.Dir}} {{$.Dir}}{{end}}' .
done | grep -v "^$main " | sort -u)
mods=$(cut -d' ' -f1-3 <<<"$pkgs" | sort -u)

# nested MODULE_DIR prints license files that sit inside the module, between a compiled package and
# the module root (vendored code with its own license, e.g. Wails' WebView2 loader).
nested() {
  local mdir=$1 d
  grep -F " $mdir " <<<"$pkgs" | cut -d' ' -f4 | while read -r d; do
    while [ "${#d}" -gt "${#mdir}" ]; do
      for f in "$d"/LICEN[CS]E* "$d"/COPYING*; do echo "$f"; done
      d=$(dirname "$d")
    done
  done | sort -u
}

classify() {
  local t; t=$(head -c 6000 "$1")
  case "$t" in
    *"Apache License"*) echo "Apache-2.0" ;;
    *"Mozilla Public License"*) echo "MPL-2.0" ;;
    *"GNU Lesser General Public"*) echo "LGPL" ;;
    *"GNU General Public"*) echo "GPL" ;;
    *"Permission is hereby granted"*) echo "MIT" ;;
    *"Redistribution and use in source"*) echo "BSD" ;;
    *"Permission to use, copy, modify, and/or distribute"*) echo "ISC" ;;
    *) echo "unknown" ;;
  esac
}

section() { # name version license-file [notice-file]
  printf '\n%s\n%s %s — %s\n%s\n\n' "================================================================================" \
    "$1" "$2" "$(classify "$3")" "================================================================================"
  cat "$3"
  if [ -n "${4:-}" ]; then printf '\n--- NOTICE ---\n\n'; cat "$4"; fi
}

{
  echo "Quay includes the following third-party software. Each component is distributed under the"
  echo "license reproduced below. (Generated by build/licenses.sh — do not edit.)"
  section "The Go programming language (standard library and runtime)" "$(go env GOVERSION)" "$(go env GOROOT)/LICENSE"
  while read -r path version dir; do
    shopt -s nullglob nocaseglob
    lic=("$dir"/LICEN[CS]E* "$dir"/COPYING*)
    notice=("$dir"/NOTICE*)
    shopt -u nullglob nocaseglob
    if [ ${#lic[@]} -eq 0 ]; then echo "no license file in $path $version" >&2; exit 1; fi
    if [ "$(classify "${lic[0]}")" = unknown ]; then echo "unrecognised license in $path $version: ${lic[0]}" >&2; exit 1; fi
    section "$path" "$version" "${lic[0]}" "${notice[0]:-}"
    shopt -s nullglob
    while read -r sub; do
      [ -n "$sub" ] || continue
      if [ "$(classify "$sub")" = unknown ]; then echo "unrecognised license: $sub" >&2; exit 1; fi
      rel=${sub#"$dir"/}
      section "$path/${rel%/*} (part of $path)" "$version" "$sub"
    done < <(nested "$dir")
    shopt -u nullglob
  done <<<"$mods"
} > "$out"

echo "wrote $out ($(grep -c '^================' "$out" | awk '{print $1/2}') components)"
